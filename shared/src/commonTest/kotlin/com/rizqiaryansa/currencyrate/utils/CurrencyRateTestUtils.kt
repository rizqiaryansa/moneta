import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.toList
import kotlinx.coroutines.launch
import kotlinx.serialization.json.Json

val testJson = Json { ignoreUnknownKeys = true }

fun <T> assertCollectingUiFlow(
    coroutineDispatcher: CoroutineDispatcher,
    flow: Flow<T>,
    block: (List<T>) -> Unit,
) {
    val scope = CoroutineScope(coroutineDispatcher)
    val testCollectorList = mutableListOf<T>()
    val uiFlowCollectorJob = scope.launch {
        flow.toList(testCollectorList)
    }
    block.invoke(testCollectorList)
    uiFlowCollectorJob.cancel()
}

fun getJsonFromFile(path: String): String = when (path) {
    CURRENCY_LIST_JSON -> MOCK_CURRENCY_LIST_JSON_CONTENT
    CURRENCY_RATE_JSON -> MOCK_CURRENCY_RATE_JSON_CONTENT
    else -> throw IllegalArgumentException("File not found: $path")
}

inline fun <reified T> parseJson(json: String): T {
    return testJson.decodeFromString(json)
}

inline fun <reified T : Any> createSuccessResponse(jsonPath: String): T {
    val mockJsonResponse = getJsonFromFile(jsonPath)
    return parseJson(mockJsonResponse)
}

